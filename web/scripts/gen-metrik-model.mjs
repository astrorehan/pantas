#!/usr/bin/env node
// Generates src/lib/metrik-model.generated.ts from
// ai_engine/outputs/metrik_yolo2.json so the numbers on /tentang/model can
// never drift from an actual validation run. Regenerate the source first with
// `python ai_engine/eval_yolo2_cls.py`, then `npm run gen:metrik`
// (also wired into predev/prebuild).

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SRC_FILE = path.resolve(__dirname, "../../ai_engine/outputs/metrik_yolo2.json");
const OUT_FILE = path.resolve(__dirname, "../src/lib/metrik-model.generated.ts");

// Sengaja tidak ada peta label di sini. Berkas ini sempat menuliskan
// "Tomat"/"Timun" ke dalam data, dan kartu di /tentang/model lalu menampilkan
// nama komoditas berbahasa Indonesia di tengah halaman berbahasa Inggris.
// Nama tampil sekarang datang dari kamus i18n, dikunci lewat `id`.

if (!existsSync(SRC_FILE)) {
  console.error(
    `gen-metrik: ${path.relative(process.cwd(), SRC_FILE)} tidak ada.\n` +
      `Jalankan dulu: python ai_engine/eval_yolo2_cls.py`,
  );
  process.exit(1);
}

const sumber = JSON.parse(readFileSync(SRC_FILE, "utf-8"));
const komoditas = sumber.komoditas ?? {};

// Pecahan mentah, bukan string sudah terformat. Versi lama menuliskan
// "97,5%" ke dalam data, sehingga halaman berbahasa Inggris menampilkan koma
// desimal Indonesia tepat di sebelah "1,860" yang komanya berarti ribuan.
const entries = Object.entries(komoditas)
  // Urut dari data validasi terbanyak: yang paling bisa dipercaya di atas.
  .sort((a, b) => b[1].jumlah_val - a[1].jumlah_val)
  .map(([id, m]) => {
    const kelas = Object.keys(m.per_kelas).sort();
    return `  {
    id: ${JSON.stringify(id)},
    arsitektur: ${JSON.stringify(m.arsitektur)},
    jumlahVal: ${m.jumlah_val},
    akurasi: ${m.akurasi},
    f1: ${m.makro.f1},
    presisi: ${m.makro.presisi},
    recall: ${m.makro.recall},
    kelas: ${JSON.stringify(kelas)},
  },`;
  });

const output = `// AUTO-GENERATED by scripts/gen-metrik-model.mjs — do NOT edit by hand.
// Source of truth: ai_engine/outputs/metrik_yolo2.json, hasil
// \`python ai_engine/eval_yolo2_cls.py\` atas split val di datasets/yolo2_ready.
// Regenerate: npm run gen:metrik

export interface MetrikKomoditas {
  /** Kunci komoditas — nama tampilnya diambil dari kamus i18n, bukan dari sini. */
  id: string;
  arsitektur: string;
  /** Jumlah gambar pada split validasi — konteks wajib untuk membaca persentase. */
  jumlahVal: number;
  /** Pecahan 0–1. Diformat saat render supaya ikut bahasa pembaca. */
  akurasi: number;
  /** Rata-rata makro antar kelas (sehat/busuk), bukan salah satu kelas saja. */
  f1: number;
  presisi: number;
  recall: number;
  /** Nama kelas apa adanya dari model (\`busuk\`, \`sehat\`). */
  kelas: string[];
}

/** Tanggal evaluasi (ISO 8601, UTC) — ditampilkan apa adanya di kartu model. */
export const METRIK_DIEVALUASI_PADA = ${JSON.stringify(sumber.dievaluasi_pada ?? "")};

export const METRIK_KOMODITAS: MetrikKomoditas[] = [
${entries.join("\n")}
];
`;

writeFileSync(OUT_FILE, output);
console.log(
  `gen-metrik: wrote ${entries.length} entries to ${path.relative(process.cwd(), OUT_FILE)}`,
);
